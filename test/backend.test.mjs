// Backend pack: contract, scaffolds, generated validators/clients and consistency checks.
import { test } from 'node:test'
import assert from 'node:assert/strict'
import fs from 'node:fs'
import path from 'node:path'
import { run, makeProject, makeMultiProject, write, read, exists, FIXTURES } from './helpers.mjs'

const be = (p, ...a) => run('backend.mjs', a, p)
const contract = (p) => JSON.parse(read(path.join(p, '.dualcraft', 'backend', 'api.json')))
const setContract = (p, c) => write(path.join(p, '.dualcraft', 'backend', 'api.json'), JSON.stringify(c, null, 2))

test('firebase: init needs a region, scaffolds functions/ and the server contract', () => {
  const p = makeProject({ mobile: 'flutter', paths: { mobile: 'app' } })
  write(path.join(p, 'firebase.json'), '{"firestore":{"rules":"firestore.rules"}}')
  assert.equal(be(p, 'init', '--provider', 'firebase').code, 1)
  const r = be(p, 'init', '--provider', 'firebase', '--region', 'europe-west1')
  assert.equal(r.code, 0, r.err)
  for (const f of ['functions/package.json', 'functions/tsconfig.json', 'functions/src/index.ts', 'functions/src/generated/api.ts']) assert.ok(exists(path.join(p, f)), f)
  assert.match(read(path.join(p, 'functions/src/generated/api.ts')), /export const REGION = "europe-west1"/)
  assert.equal(JSON.parse(read(path.join(p, 'firebase.json'))).functions[0].source, 'functions')
})

test('add: declares, scaffolds once, exports and validates the contract', () => {
  const p = makeProject({ mobile: 'flutter', paths: { mobile: 'app' } })
  be(p, 'init', '--provider', 'firebase', '--region', 'europe-west1')
  const r = be(p, 'add', 'redeemCode', '--kind', 'callable', '--desc', 'Canjea')
  assert.equal(r.code, 0, r.err)
  const src = read(path.join(p, 'functions/src/redeemCode.ts'))
  assert.match(src, /onCall\(\{ region: REGION, enforceAppCheck: true \}/)
  assert.match(src, /HttpsError\('unauthenticated'/)
  assert.match(src, /parseRedeemCodeInput\(request\.data\)/)
  assert.match(read(path.join(p, 'functions/src/index.ts')), /export \{ redeemCode \} from '.\/redeemCode'/)
  assert.equal(be(p, 'add', 'redeemCode', '--kind', 'callable').code, 1, 'duplicate refused')
  assert.equal(be(p, 'add', 'bad', '--kind', 'trigger', '--on', 'firestore.created').code, 1, 'trigger without path refused')
  assert.equal(be(p, 'add', 'nightly', '--kind', 'schedule', '--cron', 'daily').code, 1, 'bad cron refused')
  assert.ok(!contract(p).functions.some((f) => f.name === 'bad' || f.name === 'nightly'))
  // webhook: signature + idempotency; secret name without a doubled suffix
  const w = be(p, 'add', 'stripeWebhook', '--kind', 'webhook')
  assert.match(w.out, /secrets:set STRIPE_WEBHOOK_SECRET/)
  const ws = read(path.join(p, 'functions/src/stripeWebhook.ts'))
  assert.match(ws, /timingSafeEqual/); assert.match(ws, /webhook_events/); assert.match(ws, /req\.rawBody/)
  // the scaffold is never overwritten
  write(path.join(p, 'functions/src/redeemCode.ts'), '// mine\n')
  be(p, 'gen')
  assert.equal(read(path.join(p, 'functions/src/redeemCode.ts')), '// mine\n')
})

test('gen: typed clients for every stack, filtered by platform, protected against hand edits', () => {
  const p = makeMultiProject('firestore')
  be(p, 'init', '--provider', 'firebase', '--region', 'europe-west1')
  be(p, 'add', 'redeemCode', '--kind', 'callable')
  be(p, 'add', 'webOnly', '--kind', 'callable', '--platforms', 'web')
  const c = contract(p)
  Object.assign(c.functions[0], JSON.parse(read(path.join(FIXTURES, 'api-redeem.json'))))
  setContract(p, c)
  assert.equal(be(p, 'gen').code, 0)
  const web = read(path.join(p, 'web/src/lib/api-client.ts'))
  const rn = read(path.join(p, 'rn/src/lib/api-client.ts'))
  assert.match(web, /webOnly: \(\): Promise<void>/)
  assert.doesNotMatch(rn, /webOnly/)
  assert.match(rn, /redeemCode: \(input: RedeemCodeInput\): Promise<RedeemCodeOutput> => transport\.call\("redeemCode", input\)/)
  assert.match(rn, /level: "gold" \| "silver-plus"/)
  const kt = read(path.join(p, 'kmp/composeApp/src/commonMain/kotlin/com/test/app/api/ApiClient.kt'))
  assert.match(kt, /^package com\.test\.app\.api$/m)
  assert.match(kt, /val `class`: Long\? = null/)
  assert.match(kt, /SILVER_PLUS\("silver-plus"\)/)
  const sw = read(path.join(p, 'iosapp/Demo/Core/Api/ApiClient.swift'))
  assert.match(sw, /var `class`: Int\? = nil/)
  assert.match(sw, /case silverPlus = "silver-plus"/)
  const server = read(path.join(p, 'functions/src/generated/api.ts'))
  assert.match(server, /"pattern":"\^\[A-Z0-9_-\]\{3,32\}\$"/)
  assert.match(server, /unknown field/)
  // hand edit → refused
  fs.appendFileSync(path.join(p, 'rn/src/lib/api-client.ts'), '// hack\n')
  assert.equal(be(p, 'gen').code, 1)
})

test('check: unimplemented, v1, region drift in server and client code, stale files', () => {
  const p = makeProject({ mobile: 'flutter', paths: { mobile: 'app' } })
  be(p, 'init', '--provider', 'firebase', '--region', 'europe-west1')
  be(p, 'add', 'redeemCode', '--kind', 'callable')
  assert.equal(be(p, 'check').code, 0, be(p, 'check').out)
  const c = contract(p); c.functions.push({ name: 'ghost', kind: 'callable', description: 'x' }); setContract(p, c)
  let r = be(p, 'check')
  assert.equal(r.code, 1)
  assert.match(r.out, /ghost: declared but not implemented/)
  assert.match(r.out, /out of date — run gen/)
  be(p, 'gen'); c.functions.pop(); setContract(p, c); be(p, 'gen')
  write(path.join(p, 'functions/src/legacy.ts'), "import * as functions from 'firebase-functions'\nexport const legacy = functions.https.onCall(async () => 1)\n")
  write(path.join(p, 'functions/src/other.ts'), "import { onCall } from 'firebase-functions/v2/https'\nexport const other = onCall({ region: 'us-central1' }, async () => 1)\n")
  write(path.join(p, 'app/lib/services/api.dart'), "final f = FirebaseFunctions.instanceFor(region: 'us-central1');\nfinal g = FirebaseFunctions.instance;\n")
  r = be(p, 'check')
  assert.equal(r.code, 1)
  assert.match(r.out, /legacy .* uses Cloud Functions v1/)
  assert.match(r.out, /other .* runs in us-central1 but the contract says europe-west1/)
  assert.match(r.out, /api\.dart:1 calls region us-central1/)
  assert.match(r.out, /uses the default region \(us-central1\)/)
  assert.match(r.out, /legacy \(.*\) is not in the contract/)
  assert.match(be(p, 'list').out, /\? legacy/)
})

