#!/usr/bin/env node
// Maintainer tool: writes the `claude plugin eval` suite under evals/ (needs Claude Code ≥ 2.1.269 to run).
//   evals/triggers/<skill>/   one case per skill: a natural request (scripts/dev/eval-triggers.json) must load that skill
//   evals/behavior/<case>/    key behaviours on a scaffolded project (start asks the mode, decisions are respected,
//                             pending work comes from the brain)
//   node scripts/dev/gen-evals.mjs [--check]     --check: exit 1 if evals/ is out of date (used by the tests)
// Every grader is deterministic (no LLM judge), so a run costs only the agent turns.
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { spawnSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..')
const EVALS = path.join(ROOT, 'evals')
const check = process.argv.includes('--check')
const triggers = JSON.parse(fs.readFileSync(path.join(ROOT, 'scripts', 'dev', 'eval-triggers.json'), 'utf8'))
const catalog = JSON.parse(fs.readFileSync(path.join(ROOT, 'catalog.json'), 'utf8'))
const packOf = Object.fromEntries(catalog.commands.map((c) => [c.name, c.pack]))

const yamlList = (xs) => `[${xs.map((x) => JSON.stringify(x)).join(', ')}]`
const skillGrader = (skill, extra = '') => `---\ntype: tool_used\ntool: Skill\ninput_match: '"skill"\\s*:\\s*"(?:[\\w-]+:)?${skill}"'\n${extra}---\n`
const NO_REAL_PROJECT = 'Eval run: there is no real project or repository behind this request and nothing must be changed. Decide how you would handle it with the tools and skills you have, then reply in one or two sentences with your next step instead of doing the work.'

const files = new Map() // relative path → content
const put = (rel, text) => files.set(rel.split(path.sep).join('/'), text)

// ---------------------------------------------------------------- trigger cases
for (const [skill, prompt] of Object.entries(triggers)) {
  if (!fs.existsSync(path.join(ROOT, 'skills', skill, 'SKILL.md'))) throw new Error(`eval-triggers.json: no skill "${skill}"`)
  put(`triggers/${skill}/prompt.md`, `---
description: "A natural request for ${skill} loads the dualcraft:${skill} skill"
tags: ${yamlList(['trigger', packOf[skill] || 'core'])}
runs: 1
max_turns: 8
timeout_seconds: 240
allowed_tools: [Read, Glob, Grep, Skill]
disallowed_tools: [Agent]
append_system_prompt: ${JSON.stringify(NO_REAL_PROJECT)}
---

${prompt}
`)
  put(`triggers/${skill}/graders/skill-loaded.md`, skillGrader(skill))
}
const missing = fs.readdirSync(path.join(ROOT, 'skills')).filter((s) => s !== 'using-dualcraft' && !triggers[s])
if (missing.length) throw new Error(`eval-triggers.json has no request for: ${missing.join(', ')}`)

// ---------------------------------------------------------------- behaviour cases (scaffolded project)
/** A small DualCraft project made with the real brain CLI, returned as { relPath: content }. */
function fixtureProject(setup) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'dualcraft-eval-'))
  const brain = (...a) => { const r = spawnSync(process.execPath, [path.join(ROOT, 'scripts', 'brain.mjs'), ...a], { cwd: dir, encoding: 'utf8' }); if (r.status !== 0) throw new Error(`brain ${a.join(' ')}: ${r.stderr}`) }
  brain('init', '--name', 'Liga', '--version', '1.2.0', '--web', 'nextjs', '--mobile', 'flutter', '--lang', 'es')
  setup(brain)
  const out = {}
  const walk = (d) => { for (const e of fs.readdirSync(d, { withFileTypes: true })) { const p = path.join(d, e.name); if (e.isDirectory()) walk(p); else if (!/state\.json$/.test(p)) out[path.relative(dir, p).split(path.sep).join('/')] = fs.readFileSync(p, 'utf8').replace(/\r\n/g, '\n').replace(/"createdAt": "[^"]+"/, '"createdAt": "2026-01-01"').replace(/^(created|updated): .*$/gm, '$1: 2026-01-01') }
  }
  walk(dir); fs.rmSync(dir, { recursive: true, force: true })
  return out
}
const scaffold = (project) => ['#!/usr/bin/env bash', '# Fixture project for this eval case (generated by scripts/dev/gen-evals.mjs).', 'set -euo pipefail', ...Object.entries(project).sort().flatMap(([rel, text]) => [`mkdir -p "$(dirname '${rel}')"`, `cat > '${rel}' <<'DUALCRAFT_EOF'`, text.replace(/\n$/, ''), 'DUALCRAFT_EOF']), ''].join('\n')

const BEHAVIOR = [
  {
    name: 'start-asks-work-mode',
    description: 'Asked to build something, DualCraft asks the work mode (bug / new development / refactor) before any code',
    prompt: 'Quiero añadir un filtro por fecha en la lista de partidos de la web.',
    project: fixtureProject(() => {}),
    graders: { 'asks-mode.md': `---\ntype: tool_used\ntool: AskUserQuestion\ninput_match: '[Rr]efactor'\n---\n` },
  },
  {
    name: 'decision-conflict',
    description: 'A request that contradicts a decision in force is flagged, naming the decision',
    prompt: 'Añade flutter_bloc para gestionar el estado de la pantalla de partidos.',
    project: fixtureProject((brain) => brain('new', 'decision', 'Estado de la app con Riverpod, nunca Bloc', '--area', 'architecture', '--body', 'Todo el estado de la app Flutter usa Riverpod. No se añaden Bloc ni Provider.')),
    graders: { 'names-decision.md': `---\ntype: regex\npattern: 'D-001|Riverpod'\n---\n` },
  },
  {
    name: 'pending-work-from-brain',
    description: '"What is pending?" is answered from the brain: the open task, not the finished one',
    prompt: '¿Qué tenemos pendiente?',
    project: fixtureProject((brain) => { brain('new', 'task', 'Filtro por fecha en la lista de partidos', '--target', '1.3.0'); brain('new', 'task', 'Pantalla de ajustes', '--target', '1.3.0'); brain('set', 'T-002', 'status=done') }),
    graders: { 'open-task.md': `---\ntype: regex\npattern: 'T-001|[Ff]iltro por fecha'\n---\n` },
  },
]
for (const b of BEHAVIOR) {
  put(`behavior/${b.name}/case.yaml`, `schema_version: "1.1"\nname: ${b.name}\ndescription: ${JSON.stringify(b.description)}\ntags: [behavior]\nruns: 1\ncontext:\n  scaffold_script: scaffold.sh\n`)
  put(`behavior/${b.name}/prompt.md`, `---\nmax_turns: 12\ntimeout_seconds: 300\nallowed_tools: [Read, Glob, Grep, Skill, AskUserQuestion]\ndisallowed_tools: [Agent]\n---\n\n${b.prompt}\n`)
  put(`behavior/${b.name}/scaffold.sh`, scaffold(b.project))
  for (const [g, text] of Object.entries(b.graders)) put(`behavior/${b.name}/graders/${g}`, text)
}
put('.gitignore', 'results/\n')
put('README.md', `# DualCraft evals (\`claude plugin eval\`, Claude Code ≥ 2.1.269)

Generated by \`node scripts/dev/gen-evals.mjs\` from \`scripts/dev/eval-triggers.json\` — edit those, not these files.

- \`triggers/<skill>\` — a natural request must load that skill (tags: \`trigger\` + its pack)
- \`behavior/<case>\` — key behaviours on a scaffolded project (tag \`behavior\`, needs \`--scaffold\`)

All graders are deterministic (no LLM judge). Cheapest run:

    claude plugin eval . --ablation none --runs 1 --tag trigger --max-cost-usd 5
    claude plugin eval . --ablation none --runs 1 --tag behavior --scaffold
`)

// ---------------------------------------------------------------- write / check
const existing = new Map()
const walk = (d) => { if (!fs.existsSync(d)) return; for (const e of fs.readdirSync(d, { withFileTypes: true })) { const p = path.join(d, e.name); if (e.isDirectory()) { if (e.name !== 'results') walk(p) } else existing.set(path.relative(EVALS, p).split(path.sep).join('/'), fs.readFileSync(p, 'utf8')) } }
walk(EVALS)
const stale = [...files].filter(([rel, text]) => existing.get(rel) !== text).map(([rel]) => rel)
const extra = [...existing.keys()].filter((rel) => !files.has(rel))
if (check) {
  if (stale.length || extra.length) { console.log(`evals/ out of date — run node scripts/dev/gen-evals.mjs (${[...stale, ...extra].slice(0, 5).join(', ')})`); process.exit(1) }
  console.log(`evals/ up to date — ${Object.keys(triggers).length} trigger cases, ${BEHAVIOR.length} behaviour cases`); process.exit(0)
}
for (const rel of extra) fs.rmSync(path.join(EVALS, rel))
for (const [rel, text] of files) { const p = path.join(EVALS, rel); fs.mkdirSync(path.dirname(p), { recursive: true }); fs.writeFileSync(p, text) }
console.log(`evals/: ${Object.keys(triggers).length} trigger cases, ${BEHAVIOR.length} behaviour cases (${stale.length} files written, ${extra.length} removed)`)
