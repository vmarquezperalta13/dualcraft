#!/usr/bin/env node
// DualCraft code generation from the schema (.dualcraft/db/schema.dbml) — the single source of truth.
//   node gen.mjs dart|ts|rules|all [--out path] [--file schema.dbml] [--stdout]
// Output paths default to config.db.{dart,ts,rules} or sensible defaults per stack.
import fs from 'node:fs'
import path from 'node:path'
import { parseDbml } from './lib/dbml.mjs'
import { project, parseArgs, die, posix } from './lib/project.mjs'

const [target = 'help', ...rest] = process.argv.slice(2)
const { opt } = parseArgs(rest)
if (target === 'help' || !['dart', 'ts', 'rules', 'all'].includes(target)) {
  console.log('node gen.mjs dart|ts|rules|all [--out path] [--file schema.dbml] [--stdout]'); process.exit(target === 'help' ? 0 : 1)
}

const { root, dir, config } = project()
const schemaFile = opt.file ? path.resolve(String(opt.file)) : path.join(dir, 'db', 'schema.dbml')
if (!fs.existsSync(schemaFile)) die(`schema not found: ${posix(schemaFile)}`)
const model = parseDbml(fs.readFileSync(schemaFile, 'utf8'))
if (model.errors.length) { model.errors.forEach((e) => console.log('✗ ' + e)); die('fix the schema errors first (er.mjs check).') }
const SRC = posix(path.relative(root, schemaFile))
const enums = Object.fromEntries(model.enums.map((e) => [e.name, e]))

// ---------- naming ----------
const words = (s) => String(s).replace(/([a-z0-9])([A-Z])/g, '$1 $2').split(/[^A-Za-z0-9]+/).filter(Boolean)
const pascal = (s) => words(s).map((w) => w[0].toUpperCase() + w.slice(1)).join('') || 'X'
const camel = (s) => { const p = pascal(s); return p[0].toLowerCase() + p.slice(1) }
const DART_RESERVED = new Set('abstract as assert async await break case catch class const continue covariant default deferred do dynamic else enum export extends extension external factory false final finally for function get hide if implements import in interface is late library mixin new null of on operator part required rethrow return set show static super switch sync this throw true try typedef var void when while with yield'.split(' '))
const dartId = (s) => { const c = camel(s); return DART_RESERVED.has(c) ? c + 'Value' : /^\d/.test(c) ? 'v' + c : c }

// ---------- type mapping ----------
function kind(baseType) {
  const t = baseType.toLowerCase()
  if (enums[baseType]) return 'enum'
  if (/^(int|integer|bigint|smallint|tinyint|serial|bigserial|int2|int4|int8)$/.test(t)) return 'int'
  if (/^(float|double|decimal|numeric|real|number|money|float4|float8)$/.test(t)) return 'double'
  if (/^(bool|boolean)$/.test(t)) return 'bool'
  if (/^(timestamp|timestamptz|datetime|date|time)$/.test(t)) return 'date'
  if (/^(json|jsonb|map|object)$/.test(t)) return 'map'
  if (/^(geopoint)$/.test(t)) return 'geo'
  if (/^(reference|ref|docref)$/.test(t)) return 'ref'
  return 'string' // varchar, text, string, uuid, char, …
}
const nullable = (f) => !f.notNull && !f.pk

// ---------- Dart ----------
function genDart() {
  const used = { date: false, ref: false }
  const dartType = (f) => {
    const k = kind(f.baseType)
    const base = { int: 'int', double: 'double', bool: 'bool', date: 'DateTime', map: 'Map<String, dynamic>', string: 'String', geo: 'Object', ref: 'String', enum: pascal(f.baseType) }[k]
    return f.isArray ? `List<${base}>` : base
  }
  const read = (f, v) => {
    const k = kind(f.baseType)
    const one = (x, opt) => ({
      int: `(${x} as num${opt ? '?' : ''})${opt ? '?' : ''}.toInt()`,
      double: `(${x} as num${opt ? '?' : ''})${opt ? '?' : ''}.toDouble()`,
      bool: `${x} as bool${opt ? '?' : ''}`,
      date: opt ? `_date(${x})` : `_date(${x})!`,
      map: opt ? `${x} == null ? null : Map<String, dynamic>.from(${x} as Map)` : `Map<String, dynamic>.from(${x} as Map)`,
      enum: opt ? `${x} == null ? null : ${pascal(f.baseType)}.fromJson(${x} as String)` : `${pascal(f.baseType)}.fromJson(${x} as String)`,
      string: `${x} as String${opt ? '?' : ''}`, ref: `_refId(${x})${opt ? '' : '!'}`, geo: `${x}${opt ? '' : ' as Object'}`,
    }[k])
    if (k === 'date') used.date = true
    if (k === 'ref') used.ref = true
    if (f.isArray) { const list = `(${v} as List).map((e) => ${one('e', false)}).toList()`; return nullable(f) ? `${v} == null ? null : ${list}` : list }
    return one(v, nullable(f))
  }
  const write = (f, v) => {
    const k = kind(f.baseType); const q = nullable(f) ? '?' : ''
    const one = (x, o) => ({ date: `${x}${o}.toIso8601String()`, enum: `${x}${o}.json` }[k] || x)
    if (f.isArray && (k === 'date' || k === 'enum')) return `${v}${q}.map((e) => ${one('e', '')}).toList()`
    return one(v, q)
  }
  const out = [`// GENERATED by DualCraft from ${SRC} — do not edit by hand.`, `// Regenerate with /dualcraft:schema after changing the schema.`, `// ignore_for_file: type=lint`, '']
  for (const e of model.enums) {
    const name = pascal(e.name)
    out.push(`enum ${name} {`)
    out.push(e.values.map((v) => `  ${dartId(v.name)}('${v.name.replace(/'/g, "\\'")}')`).join(',\n') + ';')
    out.push(`  const ${name}(this.json);`, '  final String json;', `  static ${name} fromJson(String v) => values.firstWhere((e) => e.json == v);`, '}', '')
  }
  for (const t of model.tables) {
    const C = pascal(t.name)
    if (t.note) out.push(...t.note.split('\n').map((l) => `/// ${l}`))
    out.push(`class ${C} {`)
    out.push(`  const ${C}({${t.fields.map((f) => `${nullable(f) ? '' : 'required '}this.${dartId(f.name)}`).join(', ')}});`, '')
    for (const f of t.fields) {
      if (f.note) out.push(`  /// ${f.note}`)
      out.push(`  final ${dartType(f)}${nullable(f) ? '?' : ''} ${dartId(f.name)};`)
    }
    out.push('', `  factory ${C}.fromJson(Map<String, dynamic> json) => ${C}(`)
    for (const f of t.fields) out.push(`        ${dartId(f.name)}: ${read(f, `json['${f.name}']`)},`)
    out.push('      );', '')
    out.push('  Map<String, dynamic> toJson() => {')
    for (const f of t.fields) out.push(`        '${f.name}': ${write(f, dartId(f.name))},`)
    out.push('      };', '')
    out.push(`  ${C} copyWith({${t.fields.map((f) => `${dartType(f)}? ${dartId(f.name)}`).join(', ')}}) => ${C}(`)
    for (const f of t.fields) out.push(`        ${dartId(f.name)}: ${dartId(f.name)} ?? this.${dartId(f.name)},`)
    out.push('      );', '}', '')
  }
  if (used.date) out.push(
    '/// Accepts DateTime, ISO strings, epoch millis and Firestore Timestamps (anything with toDate()).',
    'DateTime? _date(dynamic v) {',
    '  if (v == null) return null;',
    '  if (v is DateTime) return v;',
    '  if (v is String) return DateTime.parse(v);',
    '  if (v is int) return DateTime.fromMillisecondsSinceEpoch(v);',
    '  try { return (v as dynamic).toDate() as DateTime; } catch (_) { return null; }',
    '}', '')
  if (used.ref) out.push(
    '/// Accepts a document id or a DocumentReference (anything with .id).',
    'String? _refId(dynamic v) {',
    '  if (v == null || v is String) return v as String?;',
    '  try { return (v as dynamic).id as String; } catch (_) { return v.toString(); }',
    '}', '')
  return out.join('\n')
}

// ---------- TypeScript ----------
function genTs() {
  const tsType = (f) => {
    const k = kind(f.baseType)
    const base = { int: 'number', double: 'number', bool: 'boolean', date: 'string', map: 'Record<string, unknown>', string: 'string', geo: '{ latitude: number; longitude: number }', ref: 'string', enum: pascal(f.baseType) }[k]
    return f.isArray ? (base.includes(' ') ? `Array<${base}>` : `${base}[]`) : base
  }
  const out = [`// GENERATED by DualCraft from ${SRC} — do not edit by hand.`, '// Regenerate with /dualcraft:schema after changing the schema.', '']
  for (const e of model.enums) {
    out.push(`export type ${pascal(e.name)} = ${e.values.map((v) => `'${v.name.replace(/'/g, "\\'")}'`).join(' | ')}`)
    out.push(`export const ${pascal(e.name)}Values = [${e.values.map((v) => `'${v.name.replace(/'/g, "\\'")}'`).join(', ')}] as const`, '')
  }
  for (const t of model.tables) {
    if (t.note) out.push('/** ' + t.note.replace(/\*\//g, '* /').replace(/\n/g, '\n * ') + ' */')
    out.push(`export interface ${pascal(t.name)} {`)
    for (const f of t.fields) {
      const docs = [f.note, kind(f.baseType) === 'date' ? 'ISO-8601 date string' : ''].filter(Boolean).join(' — ')
      if (docs) out.push(`  /** ${docs.replace(/\*\//g, '* /')} */`)
      const key = /^[A-Za-z_$][\w$]*$/.test(f.name) ? f.name : `'${f.name}'`
      out.push(`  ${key}${nullable(f) ? '?' : ''}: ${tsType(f)}${nullable(f) ? ' | null' : ''}`)
    }
    out.push('}', '')
  }
  return out.join('\n')
}

// ---------- Firestore rules skeleton ----------
function genRules() {
  const check = (f, v) => {
    const k = kind(f.baseType)
    if (f.isArray) return `${v} is list`
    return {
      int: `${v} is int`, double: `${v} is number`, bool: `${v} is bool`, date: `${v} is timestamp`, map: `${v} is map`,
      string: `${v} is string`, geo: `${v} is latlng`, ref: `(${v} is string || ${v} is path)`,
      enum: `${v} in [${(enums[f.baseType]?.values || []).map((x) => `'${x.name}'`).join(', ')}]`,
    }[k]
  }
  const RULES_RESERVED = new Set(['class', 'function', 'match', 'allow', 'if', 'in', 'is', 'return', 'true', 'false', 'null', 'let', 'service', 'rules_version'])
  const acc = (n) => (/^[A-Za-z_]w*$/.test(n) && !RULES_RESERVED.has(n) ? `d.${n}` : `d['${n}']`)
  const out = [
    "rules_version = '2';",
    `// GENERATED SKELETON by DualCraft from ${SRC}.`,
    '// It only validates shapes and types. Review access rules (who can read/write) before using it —',
    '// never deploy it as-is. Copy what you need into firestore.rules.',
    'service cloud.firestore {',
    '  match /databases/{database}/documents {',
    '    function isSignedIn() { return request.auth != null; }',
    '',
  ]
  for (const t of model.tables) {
    const pathNote = (t.note.match(/path:\s*([^\s,;]+)/) || [])[1]
    const segs = (pathNote || t.name).split('/').filter(Boolean)
    if (segs.length % 2 === 0) segs.pop() // a document path given: use its collection
    const matchPath = segs.map((s, i) => (i % 2 === 1 && !s.startsWith('{') ? `{${s}}` : s)).join('/') + `/{${camel(t.name)}Id}`
    const data = t.fields.filter((f) => !f.pk) // the primary key is the document id
    const req = data.filter((f) => f.notNull).map((f) => `'${f.name}'`)
    const all = data.map((f) => `'${f.name}'`)
    const fn = `valid${pascal(t.name)}`
    out.push(`    // ${t.name}${t.note ? ' — ' + t.note.split('\n')[0] : ''}`)
    out.push(`    match /${matchPath} {`)
    out.push('      allow read: if isSignedIn(); // TODO: restrict')
    out.push(`      allow create, update: if isSignedIn() && ${fn}(request.resource.data); // TODO: ownership`)
    out.push('      allow delete: if false; // TODO')
    out.push('    }')
    out.push(`    function ${fn}(d) {`)
    const conds = [`d.keys().hasOnly([${all.join(', ')}])`]
    if (req.length) conds.push(`d.keys().hasAll([${req.join(', ')}])`)
    for (const f of data) {
      const c = check(f, acc(f.name))
      conds.push(f.notNull ? c : `(!('${f.name}' in d) || ${acc(f.name)} == null || ${c})`)
    }
    out.push(`      return ${conds.join('\n        && ')};`)
    out.push('    }', '')
  }
  out.push('  }', '}', '')
  return out.join('\n')
}

// ---------- write ----------
const stackDir = (k) => path.join(root, config.paths?.[k] || '')
function defaultOut(t) {
  const c = config.db?.[t]
  if (c) return path.join(root, c)
  if (t === 'dart') return path.join(stackDir('mobile'), 'lib', 'generated', 'db_models.dart')
  if (t === 'ts') { const w = stackDir('web'); return path.join(w, fs.existsSync(path.join(w, 'src')) ? 'src' : '', 'types', 'db.ts') }
  return path.join(root, 'firestore.rules.generated')
}
const gens = { dart: genDart, ts: genTs, rules: genRules }
let targets = target === 'all' ? ['dart', 'ts', 'rules'] : [target]
if (target === 'all') {
  targets = targets.filter((t) => (t === 'dart' ? config.stacks?.mobile === 'flutter' : t === 'ts' ? !!config.stacks?.web : model.database === 'firestore'))
  if (!targets.length) die('nothing to generate for this project (no flutter/web stack, database_type is not Firestore).')
}
for (const t of targets) {
  const code = gens[t]()
  if (opt.stdout) { console.log(code); continue }
  const out = opt.out && targets.length === 1 ? path.resolve(String(opt.out)) : defaultOut(t)
  fs.mkdirSync(path.dirname(out), { recursive: true })
  fs.writeFileSync(out, code)
  console.log(`${t.padEnd(5)} → ${posix(path.relative(root, out))}`)
}
