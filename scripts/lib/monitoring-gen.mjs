// Code templates for error monitoring: the same settings in every stack (release name, environment, sample rate,
// errors to ignore, personal data off) and a scrubber that redacts sensitive keys before a report leaves the device.
// No SDK import: the app's own setup (Sentry.init / Crashlytics) reads these values — see references/monitoring.md.

const js = (v) => JSON.stringify(v)
const dq = (s) => JSON.stringify(s)
const kt = (s) => JSON.stringify(s).replace(/\$/g, '\\$')
const dart = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$')}'`
const num = (n) => (Number.isInteger(n) ? n + '.0' : String(n))

/** m: { provider, release, dsnEnv, sampleRate: {production, other}, sendPii, scrub[], ignore[], consent } */
export function tsMonitoring(m) {
  return [
    '// Error monitoring settings — generated by DualCraft from .dualcraft/monitoring/monitoring.json. Do not edit: change the spec and run monitoring.mjs gen.',
    '// Use them in your Sentry.init / Crashlytics setup (references/monitoring.md); scrubReport() is the beforeSend.',
    `export const monitoring = {`,
    `  provider: ${js(m.provider)},`,
    `  /** \`<app>@<version>\`: the same name the build uploads source maps / symbols under. */`,
    `  release: ${js(m.release)},`,
    `  /** Environment variable that holds the DSN (never commit it). */`,
    `  dsnEnv: ${js(m.dsnEnv)},`,
    `  sendDefaultPii: ${m.sendPii},`,
    `  /** Collect only after the user agrees (legal: consent). */`,
    `  requiresConsent: ${m.consent},`,
    `  ignoreErrors: ${js(m.ignore)} as string[],`,
    '} as const',
    '',
    '/** "production" for production builds, the given name otherwise ("preview", "dev"…). */',
    'export function monitoringEnvironment(env: string | undefined): string { return !env || env === \'prod\' ? \'production\' : env }',
    `export function tracesSampleRate(environment: string): number { return environment === 'production' ? ${m.sampleRate.production} : ${m.sampleRate.other} }`,
    '',
    `const SENSITIVE = new RegExp(${js(m.scrub.map((s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|'))}, 'i')`,
    '/** Copy of a report with every sensitive key (password, token, email…) replaced by "[redacted]", at any depth. */',
    'export function scrubReport<T>(value: T): T {',
    '  const walk = (v: unknown, depth: number): unknown => {',
    '    if (depth > 12 || v === null || typeof v !== \'object\') return v',
    '    if (Array.isArray(v)) return v.map((x) => walk(x, depth + 1))',
    '    const out: Record<string, unknown> = {}',
    '    for (const [k, x] of Object.entries(v as Record<string, unknown>)) out[k] = SENSITIVE.test(k) ? \'[redacted]\' : walk(x, depth + 1)',
    '    return out',
    '  }',
    '  return walk(value, 0) as T',
    '}',
    '/** False for errors the spec ignores (noise you cannot act on). */',
    'export function shouldReport(message: string | undefined): boolean { return !message || !monitoring.ignoreErrors.some((p) => message.includes(p)) }',
    '',
  ].join('\n')
}

export function dartMonitoring(m) {
  return [
    '// Error monitoring settings — generated by DualCraft from .dualcraft/monitoring/monitoring.json. Do not edit: change the spec and run monitoring.mjs gen.',
    '// Use them in your SentryFlutter.init / Crashlytics setup (references/monitoring.md); scrubReport() is the beforeSend.',
    '// ignore_for_file: public_member_api_docs',
    '',
    'class Monitoring {',
    '  Monitoring._();',
    `  static const String provider = ${dart(m.provider)};`,
    '  /// `<app>@<version>`: the same name the build uploads symbols under.',
    `  static const String release = ${dart(m.release)};`,
    '  /// --dart-define that holds the DSN (never commit it).',
    `  static const String dsnDefine = ${dart(m.dsnEnv)};`,
    `  static const bool sendDefaultPii = ${m.sendPii};`,
    '  /// Collect only after the user agrees (legal: consent).',
    `  static const bool requiresConsent = ${m.consent};`,
    `  static const List<String> ignoreErrors = <String>[${m.ignore.map(dart).join(', ')}];`,
    '',
    "  static String environment(String? env) => env == null || env.isEmpty || env == 'prod' ? 'production' : env;",
    `  static double tracesSampleRate(String environment) => environment == 'production' ? ${num(m.sampleRate.production)} : ${num(m.sampleRate.other)};`,
    '',
    `  static final RegExp _sensitive = RegExp(${dart(m.scrub.map((s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|'))}, caseSensitive: false);`,
    '',
    '  /// Copy of a report with every sensitive key (password, token, email…) replaced by "[redacted]", at any depth.',
    '  static Object? scrubReport(Object? value, [int depth = 0]) {',
    '    if (depth > 12) return value;',
    "    if (value is Map) return value.map((k, v) => MapEntry(k, k is String && _sensitive.hasMatch(k) ? '[redacted]' : scrubReport(v, depth + 1)));",
    '    if (value is List) return value.map((v) => scrubReport(v, depth + 1)).toList();',
    '    return value;',
    '  }',
    '',
    '  /// False for errors the spec ignores (noise you cannot act on).',
    '  static bool shouldReport(String? message) => message == null || !ignoreErrors.any(message.contains);',
    '}',
    '',
  ].join('\n')
}

export function kotlinMonitoring(m, pkg) {
  return [
    `package ${pkg}`,
    '',
    '// Error monitoring settings — generated by DualCraft from .dualcraft/monitoring/monitoring.json. Do not edit: change the spec and run monitoring.mjs gen.',
    '// Use them in your Sentry / Crashlytics setup (references/monitoring.md); scrubReport() is the beforeSend.',
    'object Monitoring {',
    `    const val PROVIDER: String = ${kt(m.provider)}`,
    '    /** `<app>@<version>`: the same name the build uploads symbols under. */',
    `    const val RELEASE: String = ${kt(m.release)}`,
    '    /** Build config field / environment variable that holds the DSN (never commit it). */',
    `    const val DSN_ENV: String = ${kt(m.dsnEnv)}`,
    `    const val SEND_DEFAULT_PII: Boolean = ${m.sendPii}`,
    '    /** Collect only after the user agrees (legal: consent). */',
    `    const val REQUIRES_CONSENT: Boolean = ${m.consent}`,
    `    val ignoreErrors: List<String> = listOf(${m.ignore.map(kt).join(', ')})`,
    '',
    '    fun environment(env: String?): String = if (env.isNullOrEmpty() || env == "prod") "production" else env',
    `    fun tracesSampleRate(environment: String): Double = if (environment == "production") ${num(m.sampleRate.production)} else ${num(m.sampleRate.other)}`,
    '',
    `    private val sensitive = Regex(${kt(m.scrub.map((s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|'))}, RegexOption.IGNORE_CASE)`,
    '',
    '    /** Copy of a report with every sensitive key (password, token, email…) replaced by "[redacted]", at any depth. */',
    '    fun scrubReport(value: Any?, depth: Int = 0): Any? = when {',
    '        depth > 12 -> value',
    '        value is Map<*, *> -> value.entries.associate { (k, v) -> k to if (k is String && sensitive.containsMatchIn(k)) "[redacted]" else scrubReport(v, depth + 1) }',
    '        value is List<*> -> value.map { scrubReport(it, depth + 1) }',
    '        else -> value',
    '    }',
    '',
    '    /** False for errors the spec ignores (noise you cannot act on). */',
    '    fun shouldReport(message: String?): Boolean = message == null || ignoreErrors.none { message.contains(it) }',
    '}',
    '',
  ].join('\n')
}

export function swiftMonitoring(m) {
  return [
    '// Error monitoring settings — generated by DualCraft from .dualcraft/monitoring/monitoring.json. Do not edit: change the spec and run monitoring.mjs gen.',
    '// Use them in your SentrySDK.start / Crashlytics setup (references/monitoring.md); scrubReport() is the beforeSend.',
    'import Foundation',
    '',
    'enum Monitoring {',
    `    static let provider = ${dq(m.provider)}`,
    '    /// `<app>@<version>`: the same name the build uploads symbols under.',
    `    static let release = ${dq(m.release)}`,
    '    /// Info.plist key / environment variable that holds the DSN (never commit it).',
    `    static let dsnKey = ${dq(m.dsnEnv)}`,
    `    static let sendDefaultPii = ${m.sendPii}`,
    '    /// Collect only after the user agrees (legal: consent).',
    `    static let requiresConsent = ${m.consent}`,
    `    static let ignoreErrors: [String] = [${m.ignore.map(dq).join(', ')}]`,
    '',
    '    static func environment(_ env: String?) -> String {',
    '        guard let env, !env.isEmpty, env != "prod" else { return "production" }',
    '        return env',
    '    }',
    `    static func tracesSampleRate(_ environment: String) -> Double { environment == "production" ? ${num(m.sampleRate.production)} : ${num(m.sampleRate.other)} }`,
    '',
    `    private static let sensitive = ${dq(m.scrub.map((s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|'))}`,
    '    private static func isSensitive(_ key: String) -> Bool { key.range(of: sensitive, options: [.regularExpression, .caseInsensitive]) != nil }',
    '',
    '    /// Copy of a report with every sensitive key (password, token, email…) replaced by "[redacted]", at any depth.',
    '    static func scrubReport(_ value: Any, depth: Int = 0) -> Any {',
    '        if depth > 12 { return value }',
    '        if let dict = value as? [String: Any] {',
    '            var out: [String: Any] = [:]',
    '            for (k, v) in dict { out[k] = isSensitive(k) ? "[redacted]" : scrubReport(v, depth: depth + 1) }',
    '            return out',
    '        }',
    '        if let list = value as? [Any] { return list.map { scrubReport($0, depth: depth + 1) } }',
    '        return value',
    '    }',
    '',
    '    /// False for errors the spec ignores (noise you cannot act on).',
    '    static func shouldReport(_ message: String?) -> Bool {',
    '        guard let message else { return true }',
    '        return !ignoreErrors.contains { message.contains($0) }',
    '    }',
    '}',
    '',
  ].join('\n')
}
