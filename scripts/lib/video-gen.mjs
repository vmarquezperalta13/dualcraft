export const componentsTsx = `// Scenes of the marketing videos (DualCraft video) — written once, yours to restyle.
// Sizes are relative to the short side of the frame (u = 1 %), so every format (9:16, 1:1, 16:9) lays out alike.
import React from 'react'
import { AbsoluteFill, Img, Sequence, spring, staticFile, useCurrentFrame, useVideoConfig } from 'remotion'
import { THEME } from './theme'
import type { Badge, Scene, VideoData } from './data'

type Of<K extends Scene['kind']> = Extract<Scene, { kind: K }>

function useUnit(): number {
  const { width, height } = useVideoConfig()
  return Math.min(width, height) / 100
}
/** 0 → 1 spring, starting \`delay\` frames into the scene. */
function useEnter(delay = 0): number {
  const frame = useCurrentFrame()
  const { fps } = useVideoConfig()
  return spring({ frame: frame - delay, fps, config: { damping: 200 } })
}
const rise = (p: number, u: number): React.CSSProperties => ({ opacity: p, transform: \`translateY(\${(1 - p) * u * 6}px)\` })

function TitleScene({ s }: { s: Of<'title'> }) {
  const u = useUnit(); const a = useEnter(); const b = useEnter(8)
  return (
    <AbsoluteFill style={{ background: THEME.primary, color: THEME.onPrimary, justifyContent: 'center', alignItems: 'center', padding: u * 8, textAlign: 'center' }}>
      <div style={{ fontSize: u * 10, fontWeight: 700, lineHeight: 1.1, ...rise(a, u) }}>{s.text}</div>
      {s.subtitle ? <div style={{ fontSize: u * 4.8, marginTop: u * 4, lineHeight: 1.3, ...rise(b, u) }}>{s.subtitle}</div> : null}
    </AbsoluteFill>
  )
}

function DeviceFrame({ image, device, u, landscape }: { image: string | null; device: 'phone' | 'browser'; u: number; landscape: boolean }) {
  const phone = device === 'phone'
  const h = landscape ? u * 82 : u * 120
  const w = phone ? h * 0.47 : h * 1.45
  const content = image ? <Img src={staticFile(image)} style={{ width: '100%', height: '100%', objectFit: 'cover', objectPosition: 'top' }} /> : <div style={{ width: '100%', height: '100%', background: THEME.muted }} />
  return phone ? (
    <div style={{ width: w, height: h, borderRadius: u * 6, border: \`\${u * 1.2}px solid \${THEME.onSurface}\`, overflow: 'hidden', background: THEME.onSurface, boxShadow: \`0 \${u * 2}px \${u * 6}px rgba(0,0,0,.25)\` }}>{content}</div>
  ) : (
    <div style={{ width: w, height: h, borderRadius: u * 2, overflow: 'hidden', background: THEME.surface, boxShadow: \`0 \${u * 2}px \${u * 6}px rgba(0,0,0,.25)\`, display: 'flex', flexDirection: 'column' }}>
      <div style={{ height: u * 4, background: THEME.muted, display: 'flex', alignItems: 'center', gap: u, paddingLeft: u * 1.5 }}>
        {[0, 1, 2].map((i) => <div key={i} style={{ width: u * 1.4, height: u * 1.4, borderRadius: '50%', background: THEME.surface }} />)}
      </div>
      <div style={{ flex: 1, overflow: 'hidden' }}>{content}</div>
    </div>
  )
}

function ScreenScene({ s }: { s: Of<'screen'> }) {
  const u = useUnit(); const { width, height } = useVideoConfig(); const landscape = width > height
  const a = useEnter(); const b = useEnter(6)
  return (
    <AbsoluteFill style={{ background: THEME.surface, color: THEME.onSurface, flexDirection: landscape ? 'row' : 'column', justifyContent: 'center', alignItems: 'center', gap: u * 6, padding: u * 6 }}>
      <div style={{ fontSize: u * 6.5, fontWeight: 700, lineHeight: 1.15, textAlign: landscape ? 'left' : 'center', maxWidth: landscape ? u * 70 : '100%', ...rise(a, u) }}>{s.caption}</div>
      <div style={rise(b, u)}><DeviceFrame image={s.image} device={s.device} u={u} landscape={landscape} /></div>
    </AbsoluteFill>
  )
}

function BulletItem({ text, index, u }: { text: string; index: number; u: number }) {
  const p = useEnter(8 + index * 8)
  return (
    <div style={{ display: 'flex', gap: u * 3, alignItems: 'baseline', ...rise(p, u) }}>
      <div style={{ width: u * 2.4, height: u * 2.4, borderRadius: '50%', background: THEME.primary, flexShrink: 0 }} />
      <div>{text}</div>
    </div>
  )
}

function BulletsScene({ s }: { s: Of<'bullets'> }) {
  const u = useUnit(); const a = useEnter()
  return (
    <AbsoluteFill style={{ background: THEME.surface, color: THEME.onSurface, justifyContent: 'center', padding: u * 9, gap: u * 4 }}>
      {s.title ? <div style={{ fontSize: u * 8, fontWeight: 700, color: THEME.primary, ...rise(a, u) }}>{s.title}</div> : null}
      <div style={{ display: 'flex', flexDirection: 'column', gap: u * 3.5, fontSize: u * 5, lineHeight: 1.3 }}>
        {s.items.map((t, i) => <BulletItem key={i} text={t} index={i} u={u} />)}
      </div>
    </AbsoluteFill>
  )
}

const BADGE: Record<Badge, string> = { 'app-store': 'App Store', 'google-play': 'Google Play' }
function CtaScene({ s }: { s: Of<'cta'> }) {
  const u = useUnit(); const a = useEnter(); const b = useEnter(10)
  return (
    <AbsoluteFill style={{ background: THEME.primary, color: THEME.onPrimary, justifyContent: 'center', alignItems: 'center', textAlign: 'center', padding: u * 8, gap: u * 5 }}>
      <div style={{ fontSize: u * 9, fontWeight: 700, lineHeight: 1.1, ...rise(a, u) }}>{s.text}</div>
      {s.sub ? <div style={{ fontSize: u * 4.5, ...rise(a, u) }}>{s.sub}</div> : null}
      <div style={{ display: 'flex', gap: u * 3, flexWrap: 'wrap', justifyContent: 'center', ...rise(b, u) }}>
        {s.badges.map((x) => <div key={x} style={{ padding: \`\${u * 2}px \${u * 4}px\`, borderRadius: u * 2, background: THEME.onPrimary, color: THEME.primary, fontSize: u * 4, fontWeight: 600 }}>{BADGE[x]}</div>)}
      </div>
    </AbsoluteFill>
  )
}

function SceneView({ s }: { s: Scene }) {
  switch (s.kind) {
    case 'title': return <TitleScene s={s} />
    case 'screen': return <ScreenScene s={s} />
    case 'bullets': return <BulletsScene s={s} />
    case 'cta': return <CtaScene s={s} />
  }
}

export const MarketingVideo: React.FC<{ data: VideoData }> = ({ data }) => {
  let from = 0
  return (
    <AbsoluteFill style={{ background: THEME.surface, fontFamily: THEME.fontFamily }}>
      {THEME.fonts.length ? <style>{THEME.fonts.map((f) => \`@font-face{font-family:"\${f.family}";src:url("\${staticFile(f.file)}");font-weight:\${f.weight};font-display:block}\`).join('')}</style> : null}
      {data.scenes.map((s, i) => {
        const frames = Math.round(s.seconds * data.fps)
        const el = <Sequence key={i} from={from} durationInFrames={frames}><SceneView s={s} /></Sequence>
        from += frames
        return el
      })}
    </AbsoluteFill>
  )
}
`
