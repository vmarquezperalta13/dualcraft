// Code templates for feature flags: one typed accessor per flag in TypeScript, Dart, Kotlin and Swift.
// The generated code never depends on a remote-config SDK: a small adapter (written once, yours) plugs the provider in
// through `source` (raw value by key, or null/undefined). Overrides (tests, QA, dev menus) win over the source; any
// missing or ill-typed value falls back to the catalog default, so a broken remote value can never crash the app.

export const camel = (k) => k.replace(/_([a-z0-9])/g, (_, c) => c.toUpperCase())
const pascal = (k) => camel(k).replace(/^./, (c) => c.toUpperCase())
const js = (v) => JSON.stringify(v)
const kt = (v) => (typeof v === 'string' ? JSON.stringify(v).replace(/\$/g, '\\$') : String(v))
const dart = (v) => (typeof v === 'string' ? `'${v.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$')}'` : String(v))
const doc = (f, c) => (f.description ? `${c} ${f.description.replace(/\s+/g, ' ')}${f.expires ? ` (remove in ${f.expires})` : ''}` : f.expires ? `${c} Remove in ${f.expires}.` : null)
const lines = (a) => a.filter((x) => x !== null && x !== undefined && x !== false).join('\n')
/** Only the coercion helpers the catalog needs (unused private helpers fail strict analyzers). */
const uses = (flags) => (t) => flags.some((f) => f.type === t)

// ---------------------------------------------------------------- TypeScript
const tsType = (f) => (f.type === 'bool' ? 'boolean' : f.type === 'string' ? (f.values ? f.values.map(js).join(' | ') : 'string') : 'number')
export function tsFlags(flags) {
  const has = uses(flags)
  return lines([
    '// Feature flags — generated by DualCraft from .dualcraft/flags/flags.json. Do not edit: change the catalog and run flags.mjs gen.',
    '// Plug your provider in once with setFlagSource(); overrides (tests, QA) win; bad or missing values fall back to the default.',
    'export type FlagSource = (key: string) => unknown',
    'let source: FlagSource = () => undefined',
    'const overrides = new Map<string, unknown>()',
    '/** Where remote values come from (Remote Config, a table, env…): raw value by key, undefined when unknown. */',
    'export function setFlagSource(s: FlagSource): void { source = s }',
    '/** Force values by flag name (tests, QA, a debug menu); pass {} to clear. */',
    'export function setFlagOverrides(values: Partial<{ [K in FlagName]: FlagValues[K] }>): void { overrides.clear(); for (const [k, v] of Object.entries(values)) overrides.set(flagKeys[k as FlagName], v) }',
    flags.length > 0 && 'function raw(key: string): unknown { return overrides.has(key) ? overrides.get(key) : source(key) }',
    has('bool') && 'function bool(key: string, d: boolean): boolean { const v = raw(key); if (typeof v === \'boolean\') return v; if (v === \'true\' || v === 1 || v === \'1\') return true; if (v === \'false\' || v === 0 || v === \'0\') return false; return d }',
    has('int') && 'function int(key: string, d: number): number { const v = raw(key); const n = typeof v === \'number\' ? v : typeof v === \'string\' && v.trim() !== \'\' ? Number(v) : NaN; return Number.isInteger(n) ? n : d }',
    has('double') && 'function num(key: string, d: number): number { const v = raw(key); const n = typeof v === \'number\' ? v : typeof v === \'string\' && v.trim() !== \'\' ? Number(v) : NaN; return Number.isFinite(n) ? n : d }',
    has('string') && 'function str<T extends string>(key: string, d: T, allowed?: readonly T[]): T { const v = raw(key); return typeof v === \'string\' && (!allowed || (allowed as readonly string[]).includes(v)) ? (v as T) : d }',
    '',
    `export const flagKeys = {\n${flags.map((f) => `  ${camel(f.key)}: ${js(f.key)},`).join('\n')}\n} as const`,
    'export type FlagName = keyof typeof flagKeys',
    `export interface FlagValues {\n${flags.map((f) => `  ${camel(f.key)}: ${tsType(f)}`).join('\n')}\n}`,
    `export const flagDefaults: FlagValues = {\n${flags.map((f) => `  ${camel(f.key)}: ${js(f.default)},`).join('\n')}\n}`,
    '',
    'export const flags = {',
    ...flags.map((f) => {
      const k = js(f.key); const d = js(f.default)
      const body = f.type === 'bool' ? `bool(${k}, ${d})` : f.type === 'int' ? `int(${k}, ${d})` : f.type === 'double' ? `num(${k}, ${d})` : f.values ? `str<${tsType(f)}>(${k}, ${d}, ${js(f.values)})` : `str(${k}, ${d})`
      return lines([doc(f, '  /**')?.concat(' */'), `  get ${camel(f.key)}(): ${tsType(f)} { return ${body} },`])
    }),
    '}',
    '',
  ])
}

// ---------------------------------------------------------------- Dart
const dType = (f) => (f.type === 'bool' ? 'bool' : f.type === 'int' ? 'int' : f.type === 'double' ? 'double' : 'String')
export function dartFlags(flags) {
  const has = uses(flags)
  return lines([
    '// Feature flags — generated by DualCraft from .dualcraft/flags/flags.json. Do not edit: change the catalog and run flags.mjs gen.',
    '// Plug your provider in once with FeatureFlags.source; overrides (tests, QA) win; bad or missing values fall back to the default.',
    '// ignore_for_file: public_member_api_docs',
    '',
    'class FeatureFlags {',
    '  FeatureFlags._();',
    '',
    '  /// Where remote values come from (Remote Config, a table…): raw value by key, null when unknown.',
    '  static Object? Function(String key) source = (_) => null;',
    '',
    '  /// Forced values by flag key (tests, QA, a debug menu).',
    '  static final Map<String, Object?> overrides = <String, Object?>{};',
    '',
    `  static const Map<String, Object> defaults = <String, Object>{\n${flags.map((f) => `    ${dart(f.key)}: ${dart(f.default)},`).join('\n')}\n  };`,
    '',
    flags.length > 0 && '  static Object? _raw(String key) => overrides.containsKey(key) ? overrides[key] : source(key);',
    has('bool') && "  static bool _bool(String key, bool d) { final v = _raw(key); if (v is bool) return v; if (v == 'true' || v == 1 || v == '1') return true; if (v == 'false' || v == 0 || v == '0') return false; return d; }",
    has('int') && '  static int _int(String key, int d) { final v = _raw(key); if (v is int) return v; if (v is double && v == v.truncateToDouble()) return v.toInt(); if (v is String) return int.tryParse(v.trim()) ?? d; return d; }',
    has('double') && '  static double _double(String key, double d) { final v = _raw(key); if (v is num) return v.toDouble(); if (v is String) return double.tryParse(v.trim()) ?? d; return d; }',
    has('string') && '  static String _string(String key, String d, [List<String>? allowed]) { final v = _raw(key); return v is String && (allowed == null || allowed.contains(v)) ? v : d; }',
    '',
    ...flags.map((f) => {
      const k = dart(f.key); const d = dart(f.default)
      const body = f.type === 'bool' ? `_bool(${k}, ${d})` : f.type === 'int' ? `_int(${k}, ${d})` : f.type === 'double' ? `_double(${k}, ${f.default % 1 === 0 ? f.default + '.0' : d})` : f.values ? `_string(${k}, ${d}, const <String>[${f.values.map(dart).join(', ')}])` : `_string(${k}, ${d})`
      return lines([doc(f, '  ///'), `  static ${dType(f)} get ${camel(f.key)} => ${body};`])
    }),
    '}',
    '',
  ])
}

// ---------------------------------------------------------------- Kotlin
const kType = (f) => (f.type === 'bool' ? 'Boolean' : f.type === 'int' ? 'Long' : f.type === 'double' ? 'Double' : 'String')
const kDefault = (f) => (f.type === 'int' ? `${f.default}L` : f.type === 'double' ? (Number.isInteger(f.default) ? `${f.default}.0` : String(f.default)) : kt(f.default))
export function kotlinFlags(flags, pkg) {
  const has = uses(flags)
  return lines([
    `package ${pkg}`,
    '',
    '// Feature flags — generated by DualCraft from .dualcraft/flags/flags.json. Do not edit: change the catalog and run flags.mjs gen.',
    '// Plug your provider in once with FeatureFlags.source; overrides (tests, QA) win; bad or missing values fall back to the default.',
    'object FeatureFlags {',
    '    /** Where remote values come from (Remote Config, a table…): raw value by key, null when unknown. */',
    '    var source: (String) -> Any? = { null }',
    '',
    '    /** Forced values by flag key (tests, QA, a debug menu). */',
    '    val overrides: MutableMap<String, Any?> = mutableMapOf()',
    '',
    `    val defaults: Map<String, Any> = mapOf(\n${flags.map((f) => `        ${kt(f.key)} to ${kDefault(f)},`).join('\n')}\n    )`,
    '',
    flags.length > 0 && '    private fun raw(key: String): Any? = if (overrides.containsKey(key)) overrides[key] else source(key)',
    has('bool') && '    private fun bool(key: String, d: Boolean): Boolean = when (val v = raw(key)) { is Boolean -> v; "true", "1", 1, 1L -> true; "false", "0", 0, 0L -> false; else -> d }',
    has('int') && '    private fun long(key: String, d: Long): Long = when (val v = raw(key)) { is Int -> v.toLong(); is Long -> v; is Double -> if (v % 1.0 == 0.0) v.toLong() else d; is String -> v.trim().toLongOrNull() ?: d; else -> d }',
    has('double') && '    private fun double(key: String, d: Double): Double = when (val v = raw(key)) { is Number -> v.toDouble(); is String -> v.trim().toDoubleOrNull() ?: d; else -> d }',
    has('string') && '    private fun string(key: String, d: String, allowed: List<String>? = null): String = (raw(key) as? String)?.takeIf { allowed == null || it in allowed } ?: d',
    '',
    ...flags.map((f) => {
      const k = kt(f.key)
      const body = f.type === 'bool' ? `bool(${k}, ${kDefault(f)})` : f.type === 'int' ? `long(${k}, ${kDefault(f)})` : f.type === 'double' ? `double(${k}, ${kDefault(f)})` : f.values ? `string(${k}, ${kDefault(f)}, listOf(${f.values.map(kt).join(', ')}))` : `string(${k}, ${kDefault(f)})`
      return lines([doc(f, '    /**')?.concat(' */'), `    val ${camel(f.key)}: ${kType(f)} get() = ${body}`])
    }),
    '}',
    '',
  ])
}

// ---------------------------------------------------------------- Swift
const sType = (f) => (f.type === 'bool' ? 'Bool' : f.type === 'int' ? 'Int' : f.type === 'double' ? 'Double' : 'String')
const sw = (v) => (typeof v === 'string' ? JSON.stringify(v) : String(v))
export function swiftFlags(flags) {
  const has = uses(flags)
  return lines([
    '// Feature flags — generated by DualCraft from .dualcraft/flags/flags.json. Do not edit: change the catalog and run flags.mjs gen.',
    '// Plug your provider in once with FeatureFlags.source; overrides (tests, QA) win; bad or missing values fall back to the default.',
    'import Foundation',
    '',
    'enum FeatureFlags {',
    '    /// Where remote values come from (Remote Config, a table…): raw value by key, nil when unknown.',
    '    nonisolated(unsafe) static var source: (String) -> Any? = { _ in nil }',
    '    /// Forced values by flag key (tests, QA, a debug menu).',
    '    nonisolated(unsafe) static var overrides: [String: Any] = [:]',
    '',
    `    static let defaults: [String: Any] = [\n${flags.map((f) => `        ${sw(f.key)}: ${f.type === 'double' && Number.isInteger(f.default) ? f.default + '.0' : sw(f.default)},`).join('\n')}\n    ]`,
    '',
    flags.length > 0 && '    private static func raw(_ key: String) -> Any? { overrides[key] ?? source(key) }',
    ...(has('bool') ? ['    private static func bool(_ key: String, _ d: Bool) -> Bool {',
    '        switch raw(key) {',
    '        case let v as Bool: return v',
    '        case let v as Int: return v == 1 ? true : v == 0 ? false : d',
    '        case let v as String: return v == "true" || v == "1" ? true : v == "false" || v == "0" ? false : d',
    '        default: return d',
    '        }',
    '    }'] : []),
    ...(has('int') ? ['    private static func int(_ key: String, _ d: Int) -> Int {',
    '        switch raw(key) {',
    '        case let v as Int: return v',
    '        case let v as Double: return v.rounded() == v ? Int(v) : d',
    '        case let v as String: return Int(v.trimmingCharacters(in: .whitespaces)) ?? d',
    '        default: return d',
    '        }',
    '    }'] : []),
    ...(has('double') ? ['    private static func double(_ key: String, _ d: Double) -> Double {',
    '        switch raw(key) {',
    '        case let v as Double: return v',
    '        case let v as Int: return Double(v)',
    '        case let v as String: return Double(v.trimmingCharacters(in: .whitespaces)) ?? d',
    '        default: return d',
    '        }',
    '    }'] : []),
    ...(has('string') ? ['    private static func string(_ key: String, _ d: String, _ allowed: [String]? = nil) -> String {',
    '        guard let v = raw(key) as? String, allowed?.contains(v) ?? true else { return d }',
    '        return v',
    '    }'] : []),
    '',
    ...flags.map((f) => {
      const k = sw(f.key)
      const d = f.type === 'double' && Number.isInteger(f.default) ? f.default + '.0' : sw(f.default)
      const body = f.type === 'bool' ? `bool(${k}, ${d})` : f.type === 'int' ? `int(${k}, ${d})` : f.type === 'double' ? `double(${k}, ${d})` : f.values ? `string(${k}, ${d}, [${f.values.map(sw).join(', ')}])` : `string(${k}, ${d})`
      return lines([doc(f, '    ///'), `    static var ${camel(f.key)}: ${sType(f)} { ${body} }`])
    }),
    '}',
    '',
  ])
}

// ---------------------------------------------------------------- providers
/** Firebase Remote Config template (firebase deploy --only remoteconfig): every flag with its default and description. */
export function remoteConfigTemplate(flags) {
  const vt = { bool: 'BOOLEAN', int: 'NUMBER', double: 'NUMBER', string: 'STRING' }
  const parameters = {}
  for (const f of flags) parameters[f.key] = { defaultValue: { value: String(f.default) }, ...(f.description ? { description: f.description.slice(0, 256) } : {}), valueType: vt[f.type] }
  return JSON.stringify({ parameters }, null, 2) + '\n'
}
/** Supabase: a read-only flags table (anyone reads, only the service role writes) seeded with the defaults. */
export function supabaseSql(flags) {
  const q = (s) => `'${String(s).replace(/'/g, "''")}'`
  return lines([
    '-- Feature flags — generated by DualCraft from .dualcraft/flags/flags.json. Add it as a migration (/dualcraft:database).',
    'create table if not exists public.feature_flags (',
    '  key text primary key,',
    '  value jsonb not null,',
    '  description text,',
    '  updated_at timestamptz not null default now()',
    ');',
    'alter table public.feature_flags enable row level security;',
    'drop policy if exists "feature flags are readable" on public.feature_flags;',
    'create policy "feature flags are readable" on public.feature_flags for select to anon, authenticated using (true);',
    '-- no insert/update/delete policies: only the service role (dashboard, server) changes flags',
    ...flags.map((f) => `insert into public.feature_flags (key, value, description) values (${q(f.key)}, ${q(JSON.stringify(f.default))}::jsonb, ${f.description ? q(f.description) : 'null'}) on conflict (key) do update set description = excluded.description;`),
    '',
  ])
}
