// Generated-file protection shared by DualCraft generators: a hash header detects hand edits.
//   code (// or /* */), markdown (<!-- -->) and JSON (an "@@x-dualcraft" string key, valid in ARB and ignored by i18n libs)
import fs from 'node:fs'
import path from 'node:path'
import crypto from 'node:crypto'
import { die, posix } from './project.mjs'

const sha = (s) => crypto.createHash('sha256').update(s.replace(/\r\n/g, '\n')).digest('hex').slice(0, 16)
const JSON_KEY = '@@x-dualcraft'

/** style: 'line' (//), 'block' (/* *\/), 'html' (<!-- -->). */
export function stamp(body, style = 'line') {
  const h = sha(body)
  return style === 'block' ? `/* dualcraft:hash=${h} */\n${body}` : style === 'html' ? `<!-- dualcraft:hash=${h} -->\n${body}` : `// dualcraft:hash=${h}\n${body}`
}

/** A JSON document carrying its own hash as its first key. */
export function jsonStamp(obj, note = 'GENERATED by DualCraft — do not edit by hand') {
  const body = JSON.stringify(obj, null, 2) + '\n'
  return JSON.stringify({ [JSON_KEY]: `hash=${sha(body)} · ${note}`, ...obj }, null, 2) + '\n'
}

function handEdited(file) {
  const cur = fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n')
  const m = cur.match(/^(?:\/\/|\/\*|<!--) dualcraft:hash=([0-9a-f]{16})(?: \*\/| -->)?\n([\s\S]*)$/)
  if (m) return sha(m[2]) !== m[1]
  if (cur.trimStart().startsWith('{')) {
    try {
      const o = JSON.parse(cur); const meta = o[JSON_KEY]
      if (typeof meta !== 'string') return null
      delete o[JSON_KEY]
      return sha(JSON.stringify(o, null, 2) + '\n') !== (meta.match(/hash=([0-9a-f]{16})/) || [])[1]
    } catch { return null }
  }
  return null // not a DualCraft file
}

export function writeGuarded(file, content, { root = process.cwd(), force = false } = {}) {
  const rel = posix(path.relative(root, file))
  if (fs.existsSync(file) && !force) {
    const edited = handEdited(file)
    if (edited === null) die(`${rel} exists and was not generated by DualCraft — use --out for another path or --force to replace it.`)
    if (edited) die(`${rel} was edited by hand after generation. Move those edits to the DualCraft source, or rerun with --force to discard them.`)
  }
  fs.mkdirSync(path.dirname(file), { recursive: true })
  fs.writeFileSync(file, content)
  return rel
}
