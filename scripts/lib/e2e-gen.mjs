// End-to-end tests from one neutral spec (.dualcraft/e2e/flows.json) → Playwright (web) and Maestro (mobile).
// Steps (one key each):
//   open "/path" | "scheme://x" | "https://…"     web: page.goto · mobile: openLink (paths become <scheme>://path)
//   tap  TEXT | {"id":"…"}                        a button, link or text (web: role/name) · a testID / resource id
//   fill TEXT|{"id"} + "with": VALUE               web: the field labelled TEXT · mobile: tap the field, then type
//   see TEXT|{"id"} · notSee TEXT|{"id"}           visible / not visible
//   url "/path"                                    web only: the current path
//   noErrors true                                  web only: no console errors or uncaught exceptions so far
//   back true · screenshot "name"                  screenshot → store raw folder + web visual regression
// TEXT = literal words, or "t:<i18n key>" (default locale), or {"t":"key", …params} for ICU {param} placeholders.
// VALUE = literal, "env:NAME" (secret from the environment) or "unique-email".
export const STEP_KINDS = ['open', 'tap', 'fill', 'see', 'notSee', 'url', 'noErrors', 'back', 'screenshot']

const q = (s) => JSON.stringify(s)
const sq = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`

/** Resolves TEXT: { text } or { id }. `tr(key, params)` gives the default-locale string. */
export function target(v, tr) {
  if (v && typeof v === 'object' && v.id) return { id: v.id }
  if (v && typeof v === 'object' && v.t) { const { t, ...params } = v; return { text: tr(t, params) } }
  if (typeof v === 'string' && v.startsWith('t:')) return { text: tr(v.slice(2), {}) }
  return { text: String(v) }
}
const kindOf = (step) => STEP_KINDS.find((k) => k in step)

/** Env vars a flow needs (to skip it when they are missing). */
export const flowEnv = (flow) => [...new Set([...(flow.requires || []), ...flow.steps.flatMap((s) => (typeof s.with === 'string' && s.with.startsWith('env:') ? [s.with.slice(4)] : []))])]

// ================================================================ Playwright
export const playwrightSupport = `// GENERATED by DualCraft (e2e) — helpers shared by the generated specs.
import { test as base, expect, type Locator, type Page } from '@playwright/test'

/** Every test collects console errors and uncaught exceptions (step "noErrors"). */
export const test = base.extend<{ consoleErrors: string[] }>({
  consoleErrors: async ({ page }, use) => {
    const errors: string[] = []
    page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()) })
    page.on('pageerror', (e) => errors.push(e.message))
    await use(errors)
  },
})
export { expect }

export const env = (name: string): string => process.env[name] ?? ''
export const uniqueEmail = (): string => \`e2e+\${Date.now()}@\${process.env.E2E_SIGNUP_DOMAIN || 'example.com'}\`

/** A button, link or text by its visible words. */
export function byText(page: Page, text: string): Locator {
  return page.getByRole('button', { name: text, exact: true }).or(page.getByRole('link', { name: text, exact: true })).or(page.getByText(text, { exact: true })).first()
}
/** A form field by its label. */
export const field = (page: Page, label: string): Locator => page.getByLabel(label, { exact: true }).first()
/** Raw screenshot for the store frames (dualcraft:screenshots); with E2E_VISUAL=1 also visual regression against the
 *  committed baseline (create it with --update-snapshots on the same OS as CI: baselines differ per platform). */
export async function shot(page: Page, name: string, rawDir: string): Promise<void> {
  await page.screenshot({ path: \`\${rawDir}/\${name}.png\`, fullPage: true })
  if (process.env.E2E_VISUAL) await expect(page).toHaveScreenshot(\`\${name}.png\`, { fullPage: true, maxDiffPixelRatio: 0.01 })
}
`

export function playwrightConfig({ baseUrl, startCommand, testDir = 'e2e' }) {
  return `// Playwright config (DualCraft e2e) — written once, yours to edit.
import { defineConfig, devices } from '@playwright/test'

const baseURL = process.env.E2E_BASE_URL || ${q(baseUrl)}

export default defineConfig({
  testDir: ${q(testDir)},
  fullyParallel: true,
  forbidOnly: !!process.env.CI,
  retries: process.env.CI ? 2 : 0,
  reporter: process.env.CI ? [['github'], ['html', { open: 'never' }]] : 'list',
  use: { baseURL, trace: 'on-first-retry', locale: process.env.E2E_LOCALE || undefined },
  projects: [
    { name: 'desktop', use: { ...devices['Desktop Chrome'] } },
    { name: 'mobile', use: { ...devices['Pixel 7'] } },
  ],
  // without E2E_BASE_URL (a preview deploy), Playwright starts the app itself
  webServer: process.env.E2E_BASE_URL ? undefined : { command: ${q(startCommand)}, url: baseURL, reuseExistingServer: !process.env.CI, timeout: 180_000 },
})
`
}

export function playwrightSpec(flow, { tr, rawDir, supportImport = './support' }) {
  const L = []
  const loc = (t) => (t.id ? `page.getByTestId(${sq(t.id)})` : `byText(page, ${sq(t.text)})`)
  const env = flowEnv(flow)
  for (const step of flow.steps) {
    const k = kindOf(step); const v = step[k]
    if (k === 'open') L.push(`  await page.goto(${sq(v)})`)
    else if (k === 'tap') L.push(`  await ${loc(target(v, tr))}.click()`)
    else if (k === 'fill') {
      const t = target(v, tr); const w = step.with
      const value = typeof w === 'string' && w.startsWith('env:') ? `env(${sq(w.slice(4))})` : w === 'unique-email' ? 'uniqueEmail()' : sq(w ?? '')
      L.push(`  await ${t.id ? `page.getByTestId(${sq(t.id)})` : `field(page, ${sq(t.text)})`}.fill(${value})`)
    } else if (k === 'see' || k === 'notSee') {
      const t = target(v, tr)
      const l = t.id ? `page.getByTestId(${sq(t.id)})` : `page.getByText(${sq(t.text)}, { exact: true }).first()`
      L.push(`  await expect(${l}).${k === 'see' ? 'toBeVisible' : 'toBeHidden'}()`)
    } else if (k === 'url') L.push(`  await expect(page).toHaveURL((u) => u.pathname === ${sq(v)})`)
    else if (k === 'noErrors') L.push('  expect(consoleErrors, \'console errors\').toEqual([])')
    else if (k === 'back') L.push('  await page.goBack()')
    else if (k === 'screenshot') L.push(`  await shot(page, ${sq(v)}, ${sq(rawDir)})`)
  }
  const used = ['test', 'expect', ...['byText', 'field', 'env', 'uniqueEmail', 'shot'].filter((h) => L.some((l) => l.includes(h + '(')) || (h === 'env' && env.length))]
  return `// GENERATED by DualCraft from .dualcraft/e2e/flows.json (flow "${flow.id}") — change the flow and run e2e.mjs gen.
import { ${used.join(', ')} } from ${q(supportImport)}

test(${sq(flow.title || flow.id)}, { tag: [${(flow.tags || []).map((t) => sq('@' + t)).join(', ')}] }, async ({ page${L.some((l) => l.includes('consoleErrors')) ? ', consoleErrors' : ''} }) => {
${env.map((e) => `  test.skip(!env(${sq(e)}), ${sq('needs ' + e)})\n`).join('')}${L.join('\n')}
})
`
}

// ================================================================ Maestro
/** Maestro matches text as a regular expression: escape the literal words. */
const rx = (s) => String(s).replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
const yq = (s) => q(s) // JSON strings are valid YAML double-quoted scalars

export function maestroFlow(flow, { tr, appId, scheme, rawDir }) {
  const L = [`- launchApp:`, `    clearState: ${flow.keepState ? 'false' : 'true'}`]
  const sel = (t) => (t.id ? [`    id: ${yq(t.id)}`] : [`    text: ${yq(rx(t.text))}`])
  for (const step of flow.steps) {
    const k = kindOf(step); const v = step[k]
    if (k === 'open') L.push(`- openLink: ${yq(/^[a-z][\w+.-]*:\/\//i.test(v) ? v : `${scheme}://${String(v).replace(/^\//, '')}`)}`)
    else if (k === 'tap') L.push('- tapOn:', ...sel(target(v, tr)))
    else if (k === 'fill') {
      L.push('- tapOn:', ...sel(target(v, tr)))
      const w = step.with
      if (w === 'unique-email') L.push('- inputRandomEmail')
      else L.push(`- inputText: ${yq(typeof w === 'string' && w.startsWith('env:') ? '${' + w.slice(4) + '}' : String(w ?? ''))}`)
      L.push('- hideKeyboard')
    } else if (k === 'see') L.push('- assertVisible:', ...sel(target(v, tr)))
    else if (k === 'notSee') L.push('- assertNotVisible:', ...sel(target(v, tr)))
    else if (k === 'back') L.push('- back')
    else if (k === 'screenshot') L.push(`- takeScreenshot: ${yq(`${rawDir}/\${maestro.platform}/${v}`)}`)
    // url / noErrors are web-only checks
  }
  L.push('- waitForAnimationToEnd')
  return `# GENERATED by DualCraft from .dualcraft/e2e/flows.json (flow "${flow.id}") — change the flow and run e2e.mjs gen.
appId: ${appId}
name: ${yq(flow.title || flow.id)}
tags:
${(flow.tags || ['e2e']).map((t) => `  - ${t}`).join('\n')}
---
${L.join('\n')}
`
}

