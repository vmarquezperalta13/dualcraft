/** iOS applinks path patterns and Android pathPattern for a route path. */
export const aasaPattern = (p) => '/' + segments(p).map((s) => (s.lit !== undefined ? s.lit : '*')).join('/')
export const androidPattern = (p) => '/' + segments(p).map((s) => (s.lit !== undefined ? s.lit.replace(/[.*\\]/g, '\\\\$&') : '.*')).join('/')
