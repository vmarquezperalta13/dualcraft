// Code templates for deep links: typed builders (route → path / https link / scheme link) and a parser (any link → typed
// route, or null) in TypeScript, Dart, Kotlin and Swift. Paths use {param} like the push catalog; params are string|int,
// query values are optional. Parsing tries the most specific routes first (/matches/new before /matches/{id}).

export const camel = (s) => s.replace(/[-_ ]+([a-zA-Z0-9])/g, (_, c) => c.toUpperCase()).replace(/^[A-Z]/, (c) => c.toLowerCase())
export const pascal = (s) => camel(s).replace(/^./, (c) => c.toUpperCase())
const js = (v) => JSON.stringify(v)
const dq = (s) => JSON.stringify(s)
const dart = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$')}'`
const ktS = (s) => JSON.stringify(s).replace(/\$/g, '\\$')

/** [{ lit } | { param }] for a path like /matches/{id}/stats. */
export const segments = (p) => p.split('/').filter(Boolean).map((s) => (/^\{(\w+)\}$/.test(s) ? { param: s.slice(1, -1) } : { lit: s }))
/** Most specific first: more segments, then literals before params, position by position. */
export function parseOrder(routes) {
  const key = (r) => segments(r.path).map((s) => (s.lit !== undefined ? '0' : '1')).join('')
  return [...routes].sort((a, b) => segments(b.path).length - segments(a.path).length || key(a).localeCompare(key(b)))
}
const fields = (r) => [...segments(r.path).filter((s) => s.param).map((s) => ({ name: s.param, type: r.params?.[s.param] || 'string', required: true })), ...Object.entries(r.query || {}).map(([name, type]) => ({ name, type, required: false, query: true }))]

// ---------------------------------------------------------------- TypeScript
export function tsLinks(spec, routes) {
  const tsT = (f) => (f.type === 'int' ? 'number' : 'string')
  const L = []
  L.push('// Deep links — generated by DualCraft from .dualcraft/links/links.json. Do not edit: change the spec and run links.mjs gen.',
    '// links.<route>(params) → path · linkUrl(path) → https link (opens the app when installed) · parseLink(url) → typed route or null.',
    `export const appLinks = { domain: ${js(spec.domain)}, scheme: ${js(spec.scheme || '')} } as const`, '')
  L.push('export type AppRoute =', ...routes.map((r) => `  | { name: ${js(r.name)}${fields(r).map((f) => `; ${camel(f.name)}${f.required ? '' : '?'}: ${tsT(f)}`).join('')} }`), '')
  L.push('const enc = (v: string | number): string => encodeURIComponent(String(v))',
    'function withQuery(path: string, q: Record<string, string | number | undefined>): string {',
    "  const s = Object.entries(q).filter(([, v]) => v !== undefined).map(([k, v]) => `${enc(k)}=${enc(v as string | number)}`).join('&')",
    "  return s ? `${path}?${s}` : path",
    '}', '')
  L.push('export const links = {')
  for (const r of routes) {
    const fs = fields(r)
    const path = '`' + (segments(r.path).map((s) => '/' + (s.lit !== undefined ? s.lit.replace(/[`$\\]/g, '\\$&') : '${enc(p.' + camel(s.param) + ')}')).join('') || '/') + '`'
    const q = fs.filter((f) => f.query)
    const arg = fs.length ? `p: { ${fs.map((f) => `${camel(f.name)}${f.required ? '' : '?'}: ${tsT(f)}`).join('; ')} }` : ''
    L.push(`  ${camel(r.name)}: (${arg}): string => ${q.length ? `withQuery(${path}, { ${q.map((f) => `${js(f.name)}: p.${camel(f.name)}`).join(', ')} })` : path},`)
  }
  L.push('}', '')
  L.push('/** https://<domain><path> (App Links / Universal Links), or <scheme>://<path> when asked and the app has a scheme. */',
    "export function linkUrl(path: string, kind: 'https' | 'scheme' = 'https'): string {",
    "  return kind === 'scheme' && appLinks.scheme ? `${appLinks.scheme}://${path.replace(/^\\//, '')}` : `https://${appLinks.domain}${path}`",
    '}', '')
  L.push('/** The route of a link (https on the app domain, the app scheme, or a bare path); null when it is not one of ours. */',
    'export function parseLink(url: string): AppRoute | null {',
    "  const dec = (v: string): string | null => { try { return decodeURIComponent(v.replace(/\\+/g, ' ')) } catch { return null } }",
    "  const m = /^([a-zA-Z][a-zA-Z0-9+.-]*):\\/\\/([^?#]*)(?:\\?([^#]*))?/.exec(url) ?? /^()(\\/[^?#]*)(?:\\?([^#]*))?/.exec(url)",
    '  if (!m) return null',
    "  const scheme = m[1].toLowerCase(); let path: string",
    "  if (scheme === 'https' || scheme === 'http') {",
    "    const host = m[2].split('/')[0].split(':')[0].toLowerCase()",
    "    if (host !== appLinks.domain && host !== 'www.' + appLinks.domain) return null",
    "    path = m[2].slice(m[2].split('/')[0].length) || '/'",
    "  } else if (scheme && appLinks.scheme && scheme === appLinks.scheme) path = '/' + m[2]",
    "  else if (!scheme) path = m[2]",
    '  else return null',
    "  const s: string[] = []; for (const part of path.split('/').filter(Boolean)) { const d = dec(part); if (d === null) return null; s.push(d) }",
    '  const query = new Map<string, string>()',
    "  for (const pair of (m[3] ?? '').split('&').filter(Boolean)) { const i = pair.indexOf('='); const k = dec(i < 0 ? pair : pair.slice(0, i)); const v = dec(i < 0 ? '' : pair.slice(i + 1)); if (k !== null && v !== null) query.set(k, v) }",
    '  const q = { get: (k: string): string | null => query.get(k) ?? null }',
    "  const int = (v: string | null): number | undefined => (v !== null && /^-?\\d+$/.test(v) ? Number(v) : undefined)",
    "  const str = (v: string | null): string | undefined => (v === null ? undefined : v)")
  for (const r of parseOrder(routes)) {
    const sg = segments(r.path)
    const conds = [`s.length === ${sg.length}`, ...sg.map((x, i) => (x.lit !== undefined ? `s[${i}] === ${js(x.lit)}` : (r.params?.[x.param] === 'int' ? `/^-?\\d+$/.test(s[${i}])` : null))).filter(Boolean)]
    const vals = [...sg.map((x, i) => (x.param ? `${camel(x.param)}: ${r.params?.[x.param] === 'int' ? `Number(s[${i}])` : `s[${i}]`}` : null)).filter(Boolean),
      ...Object.entries(r.query || {}).map(([k, t]) => `...(${t === 'int' ? 'int' : 'str'}(q.get(${js(k)})) !== undefined ? { ${camel(k)}: ${t === 'int' ? 'int' : 'str'}(q.get(${js(k)}))! } : {})`)]
    L.push(`  if (${conds.join(' && ')}) return { name: ${js(r.name)}${vals.length ? ', ' + vals.join(', ') : ''} }`)
  }
  L.push('  return null', '}', '')
  return L.join('\n')
}

// ---------------------------------------------------------------- Dart
export function dartLinks(spec, routes) {
  const dT = (f) => (f.type === 'int' ? 'int' : 'String')
  const L = ['// Deep links — generated by DualCraft from .dualcraft/links/links.json. Do not edit: change the spec and run links.mjs gen.',
    '// AppRoute subclasses → path / https link · AppRoute.parse(url) → typed route or null.',
    '// ignore_for_file: public_member_api_docs', '',
    'class AppLinks {', '  AppLinks._();', `  static const String domain = ${dart(spec.domain)};`, `  static const String scheme = ${dart(spec.scheme || '')};`,
    '  /// https://<domain><path> (App Links / Universal Links), or <scheme>://<path> when asked and the app has a scheme.',
    "  static String url(AppRoute route, {bool useScheme = false}) => useScheme && scheme.isNotEmpty ? '$scheme://${route.path.substring(1)}' : 'https://$domain${route.path}';",
    '}', '',
    'String _withQuery(String path, Map<String, Object?> q) {',
    "  final s = q.entries.where((e) => e.value != null).map((e) => '${Uri.encodeQueryComponent(e.key)}=${Uri.encodeQueryComponent(e.value.toString())}').join('&');",
    "  return s.isEmpty ? path : '$path?$s';",
    '}', '',
    'List<String>? _segments(String path) {',
    "  try { return path.split('/').where((x) => x.isNotEmpty).map(Uri.decodeComponent).toList(); } catch (_) { return null; }",
    '}', '',
    'sealed class AppRoute {', '  const AppRoute();', '  String get path;', '',
    '  /// The route of a link (https on the app domain, the app scheme, or a bare path); null when it is not one of ours.',
    '  static AppRoute? parse(String url) {',
    '    final u = Uri.tryParse(url);', '    if (u == null) return null;', '    final String path;',
    "    if (u.scheme == 'https' || u.scheme == 'http') {",
    "      if (u.host != AppLinks.domain && u.host != 'www.${AppLinks.domain}') return null;", '      path = u.path;',
    "    } else if (AppLinks.scheme.isNotEmpty && u.scheme == AppLinks.scheme) {",
    "      path = '/${[u.host, u.path.replaceFirst(RegExp(r'^/'), '')].where((x) => x.isNotEmpty).join('/')}';",
    "    } else if (u.scheme.isEmpty) {", '      path = u.path;', '    } else {', '      return null;', '    }',
    '    final s = _segments(path);',
    '    if (s == null) return null;',
    '    final q = u.queryParameters;']
  for (const r of parseOrder(routes)) {
    const sg = segments(r.path)
    const conds = [`s.length == ${sg.length}`, ...sg.map((x, i) => (x.lit !== undefined ? `s[${i}] == ${dart(x.lit)}` : (r.params?.[x.param] === 'int' ? `int.tryParse(s[${i}]) != null` : null))).filter(Boolean)]
    const args = [...sg.map((x, i) => (x.param ? `${camel(x.param)}: ${r.params?.[x.param] === 'int' ? `int.parse(s[${i}])` : `s[${i}]`}` : null)).filter(Boolean),
      ...Object.entries(r.query || {}).map(([k, t]) => `${camel(k)}: ${t === 'int' ? `int.tryParse(q[${dart(k)}] ?? '')` : `q[${dart(k)}]`}`)]
    L.push(`    if (${conds.join(' && ')}) return ${pascal(r.name)}Route(${args.join(', ')});`)
  }
  L.push('    return null;', '  }', '}', '')
  for (const r of routes) {
    const fs = fields(r); const C = pascal(r.name) + 'Route'
    const path = "'" + (segments(r.path).map((s) => '/' + (s.lit !== undefined ? s.lit.replace(/[\\'$]/g, '\\$&') : '${Uri.encodeComponent(' + camel(s.param) + (r.params?.[s.param] === 'int' ? '.toString()' : '') + ')}')).join('') || '/') + "'"
    const q = fs.filter((f) => f.query)
    L.push(`final class ${C} extends AppRoute {`, `  const ${C}(${fs.length ? '{' + fs.map((f) => (f.required ? `required this.${camel(f.name)}` : `this.${camel(f.name)}`)).join(', ') + '}' : ''});`,
      ...fs.map((f) => `  final ${dT(f)}${f.required ? '' : '?'} ${camel(f.name)};`),
      '  @override', `  String get path => ${q.length ? `_withQuery(${path}, {${q.map((f) => `${dart(f.name)}: ${camel(f.name)}`).join(', ')}})` : path};`,
      '  @override', `  bool operator ==(Object other) => other is ${C}${fs.map((f) => ` && other.${camel(f.name)} == ${camel(f.name)}`).join('')};`,
      '  @override', `  int get hashCode => ${fs.length ? `Object.hash(${dart(r.name)}, ${fs.map((f) => camel(f.name)).join(', ')})` : `${dart(r.name)}.hashCode`};`,
      '}', '')
  }
  return L.join('\n')
}

// ---------------------------------------------------------------- Kotlin (common code: no java.net, works in KMP)
export function kotlinLinks(spec, routes, pkg) {
  const kT = (f) => (f.type === 'int' ? 'Long' : 'String')
  const L = [`package ${pkg}`, '',
    '// Deep links — generated by DualCraft from .dualcraft/links/links.json. Do not edit: change the spec and run links.mjs gen.',
    '// AppRoute subclasses → path / https link · AppRoute.parse(url) → typed route or null. Pure Kotlin (common code).',
    'object AppLinks {', `    const val DOMAIN: String = ${ktS(spec.domain)}`, `    const val SCHEME: String = ${ktS(spec.scheme || '')}`,
    '    /** https://<domain><path> (App Links / Universal Links), or <scheme>://<path> when asked and the app has a scheme. */',
    '    fun url(route: AppRoute, useScheme: Boolean = false): String = if (useScheme && SCHEME.isNotEmpty()) "$SCHEME://${route.path.removePrefix("/")}" else "https://$DOMAIN${route.path}"',
    '',
    '    private const val HEX = "0123456789ABCDEF"',
    '    internal fun encode(v: String): String = buildString { for (b in v.encodeToByteArray()) { val c = b.toInt() and 0xFF; if ((c in 0x30..0x39) || (c in 0x41..0x5A) || (c in 0x61..0x7A) || c == 0x2D || c == 0x2E || c == 0x5F || c == 0x7E) append(c.toChar()) else { append(\'%\'); append(HEX[c shr 4]); append(HEX[c and 15]) } } }',
    '    internal fun decode(v: String): String? {',
    '        val out = ArrayList<Byte>(v.length); var i = 0',
    '        while (i < v.length) { val ch = v[i]; if (ch == \'%\') { if (i + 2 >= v.length) return null; val n = v.substring(i + 1, i + 3).toIntOrNull(16) ?: return null; out.add(n.toByte()); i += 3 } else if (ch == \'+\') { out.add(0x20); i++ } else { out.addAll(ch.toString().encodeToByteArray().toList()); i++ } }',
    '        return out.toByteArray().decodeToString()',
    '    }',
    '    internal fun withQuery(path: String, q: List<Pair<String, Any?>>): String { val s = q.filter { it.second != null }.joinToString("&") { "${encode(it.first)}=${encode(it.second.toString())}" }; return if (s.isEmpty()) path else "$path?$s" }',
    '}', '',
    'sealed class AppRoute {', '    abstract val path: String', '']
  for (const r of routes) {
    const fs = fields(r); const C = pascal(r.name)
    const path = '"' + (segments(r.path).map((s) => '/' + (s.lit !== undefined ? s.lit.replace(/["\\$]/g, '\\$&') : '${AppLinks.encode(' + camel(s.param) + (r.params?.[s.param] === 'int' ? '.toString()' : '') + ')}')).join('') || '/') + '"'
    const q = fs.filter((f) => f.query)
    const body = `override val path: String get() = ${q.length ? `AppLinks.withQuery(${path}, listOf(${q.map((f) => `${ktS(f.name)} to ${camel(f.name)}`).join(', ')}))` : path}`
    L.push(fs.length ? `    data class ${C}(${fs.map((f) => `val ${camel(f.name)}: ${kT(f)}${f.required ? '' : '? = null'}`).join(', ')}) : AppRoute() { ${body} }` : `    data object ${C} : AppRoute() { ${body} }`)
  }
  L.push('', '    companion object {',
    '        /** The route of a link (https on the app domain, the app scheme, or a bare path); null when it is not one of ours. */',
    '        fun parse(url: String): AppRoute? {',
    '            val schemeEnd = url.indexOf("://")',
    '            val scheme = if (schemeEnd > 0) url.substring(0, schemeEnd).lowercase() else ""',
    '            val rest = if (schemeEnd > 0) url.substring(schemeEnd + 3) else url',
    '            val noFrag = rest.substringBefore(\'#\')',
    '            val beforeQuery = noFrag.substringBefore(\'?\')',
    '            val query = if (noFrag.contains(\'?\')) noFrag.substringAfter(\'?\') else ""',
    '            val path: String = when {',
    '                scheme == "https" || scheme == "http" -> { val host = beforeQuery.substringBefore(\'/\').substringBefore(\':\').lowercase(); if (host != AppLinks.DOMAIN && host != "www." + AppLinks.DOMAIN) return null; "/" + beforeQuery.substringAfter(\'/\', "") }',
    '                AppLinks.SCHEME.isNotEmpty() && scheme == AppLinks.SCHEME.lowercase() -> "/$beforeQuery"',
    '                scheme.isEmpty() -> beforeQuery',
    '                else -> return null',
    '            }',
    '            val s = path.split(\'/\').filter { it.isNotEmpty() }.map { AppLinks.decode(it) ?: return null }',
    '            val q = query.split(\'&\').filter { it.isNotEmpty() }.associate { p -> (AppLinks.decode(p.substringBefore(\'=\')) ?: "") to (AppLinks.decode(p.substringAfter(\'=\', "")) ?: "") }')
  for (const r of parseOrder(routes)) {
    const sg = segments(r.path)
    const conds = [`s.size == ${sg.length}`, ...sg.map((x, i) => (x.lit !== undefined ? `s[${i}] == ${ktS(x.lit)}` : (r.params?.[x.param] === 'int' ? `s[${i}].toLongOrNull() != null` : null))).filter(Boolean)]
    const args = [...sg.map((x, i) => (x.param ? `${camel(x.param)} = ${r.params?.[x.param] === 'int' ? `s[${i}].toLong()` : `s[${i}]`}` : null)).filter(Boolean),
      ...Object.entries(r.query || {}).map(([k, t]) => `${camel(k)} = ${t === 'int' ? `q[${ktS(k)}]?.toLongOrNull()` : `q[${ktS(k)}]`}`)]
    L.push(`            if (${conds.join(' && ')}) return ${segments(r.path).some((x) => x.param) || Object.keys(r.query || {}).length ? `${pascal(r.name)}(${args.join(', ')})` : pascal(r.name)}`)
  }
  L.push('            return null', '        }', '    }', '}', '')
  return L.join('\n')
}

// ---------------------------------------------------------------- Swift
export function swiftLinks(spec, routes) {
  const sT = (f) => (f.type === 'int' ? 'Int' : 'String')
  const caseOf = (r) => { const fs = fields(r); return fs.length ? `case ${camel(r.name)}(${fs.map((f) => `${camel(f.name)}: ${sT(f)}${f.required ? '' : '?'}`).join(', ')})` : `case ${camel(r.name)}` }
  const L = ['// Deep links — generated by DualCraft from .dualcraft/links/links.json. Do not edit: change the spec and run links.mjs gen.',
    '// AppRoute cases → path / https link · AppRoute.parse(url) → typed route or nil.',
    'import Foundation', '',
    'enum AppLinks {', `    static let domain = ${dq(spec.domain)}`, `    static let scheme = ${dq(spec.scheme || '')}`,
    '    /// https://<domain><path> (App Links / Universal Links), or <scheme>://<path> when asked and the app has a scheme.',
    '    static func url(_ route: AppRoute, useScheme: Bool = false) -> String {',
    '        useScheme && !scheme.isEmpty ? "\\(scheme)://\\(route.path.dropFirst())" : "https://\\(domain)\\(route.path)"',
    '    }',
    '    static let unreserved = CharacterSet(charactersIn: "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-._~")',
    '    static func encode(_ v: String) -> String { v.addingPercentEncoding(withAllowedCharacters: unreserved) ?? v }',
    '    static func withQuery(_ path: String, _ q: [(String, String?)]) -> String {',
    '        let s = q.compactMap { pair in pair.1.map { "\\(encode(pair.0))=\\(encode($0))" } }.joined(separator: "&")',
    '        return s.isEmpty ? path : "\\(path)?\\(s)"',
    '    }',
    '}', '',
    'enum AppRoute: Equatable {', ...routes.map((r) => '    ' + caseOf(r)), '',
    '    var path: String {', '        switch self {']
  for (const r of routes) {
    const fs = fields(r); const q = fs.filter((f) => f.query)
    const path = '"' + (segments(r.path).map((s) => '/' + (s.lit !== undefined ? s.lit.replace(/["\\]/g, '\\$&') : '\\(AppLinks.encode(' + (r.params?.[s.param] === 'int' ? `String(${camel(s.param)})` : camel(s.param)) + '))')).join('') || '/') + '"'
    const bind = fs.length ? `(${fs.map((f) => `let ${camel(f.name)}`).join(', ')})` : ''
    L.push(`        case .${camel(r.name)}${bind}:`, `            return ${q.length ? `AppLinks.withQuery(${path}, [${q.map((f) => `(${dq(f.name)}, ${f.type === 'int' ? `${camel(f.name)}.map { String($0) }` : camel(f.name)})`).join(', ')}])` : path}`)
  }
  L.push('        }', '    }', '',
    '    /// The route of a link (https on the app domain, the app scheme, or a bare path); nil when it is not one of ours.',
    '    static func parse(_ url: String) -> AppRoute? {',
    '        guard let c = URLComponents(string: url) else { return nil }',
    '        let scheme = c.scheme?.lowercased() ?? ""',
    '        let path: String',
    '        if scheme == "https" || scheme == "http" {',
    '            let host = c.host?.lowercased() ?? ""',
    '            guard host == AppLinks.domain || host == "www." + AppLinks.domain else { return nil }',
    '            path = c.path',
    '        } else if !AppLinks.scheme.isEmpty && scheme == AppLinks.scheme.lowercased() {',
    '            path = "/" + [c.host ?? "", String(c.path.drop(while: { $0 == "/" }))].filter { !$0.isEmpty }.joined(separator: "/")',
    '        } else if scheme.isEmpty {',
    '            path = c.path',
    '        } else { return nil }',
    '        let s = path.split(separator: "/").map(String.init)',
    '        var q: [String: String] = [:]',
    '        for item in c.queryItems ?? [] { q[item.name] = item.value ?? "" }')
  for (const r of parseOrder(routes)) {
    const sg = segments(r.path)
    const conds = [`s.count == ${sg.length}`, ...sg.map((x, i) => (x.lit !== undefined ? `s[${i}] == ${dq(x.lit)}` : (r.params?.[x.param] === 'int' ? `Int(s[${i}]) != nil` : null))).filter(Boolean)]
    const fs = fields(r)
    const args = [...sg.map((x, i) => (x.param ? `${camel(x.param)}: ${r.params?.[x.param] === 'int' ? `Int(s[${i}])!` : `s[${i}]`}` : null)).filter(Boolean),
      ...Object.entries(r.query || {}).map(([k, t]) => `${camel(k)}: ${t === 'int' ? `q[${dq(k)}].flatMap { Int($0) }` : `q[${dq(k)}]`}`)]
    L.push(`        if ${conds.join(', ')} { return .${camel(r.name)}${fs.length ? `(${args.join(', ')})` : ''} }`)
  }
  L.push('        return nil', '    }', '}', '')
  return L.join('\n')
}

